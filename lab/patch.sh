#!/bin/sh
# Cosmetic attacker patch for TracerPIN. It changes labels and the trace
# pathname but deliberately does not modify Pin's code-cache allocation or
# internal descriptor use. See docs/WRITEUP.md for the structural next rung.
set -eu

cd /root/tracer
fail()
{
    echo "patch.sh: unsupported TracerPIN source: $*" >&2
    exit 1
}

grep -Fq 'Instruction Trace Generated By Roswell TracerPin' Tracer.cpp || \
    fail 'banner anchor not found'
grep -Fq 'TraceFile.open(TraceName.c_str());' Tracer.cpp || \
    fail 'trace-open anchor not found'
grep -Fq 'Tracer.so' Makefile || fail 'Tracer.so Makefile anchor not found'
grep -Fq 'Tracer.so' Tracer || fail 'Tracer.so launcher anchor not found'

sed -i \
    's/Instruction Trace Generated By Roswell TracerPin/System Trace Logger/' \
    Tracer.cpp
sed -i \
    '/TraceFile.open(TraceName.c_str());/a\            unlink(TraceName.c_str());' \
    Tracer.cpp
if ! grep -Fq '#include <unistd.h>' Tracer.cpp; then
    sed -i 's|#include <fcntl.h>|#include <fcntl.h>\n#include <unistd.h>|' \
        Tracer.cpp
fi
sed -i 's/Tracer\.so/libsysmon.so/g' Makefile Tracer

make
make install
rm -f /usr/local/bin/Tracer /usr/local/bin/obj-*/Tracer.so
cp -a Tracer /usr/local/bin/kworkerd
test -x /usr/local/bin/kworkerd || fail 'launcher installation failed'
echo "cosmetic tracer patch installed as kworkerd"
